export function Screener({ initialFocus = '', onResearch, onSave }) {
  const initial = () => ({ ...emptyForm(initialFocus ? 'bond' : 'stock'), query: initialFocus });
  const [draft, setDraft] = useState(initial);
  const [active, setActive] = useState(initial);
  const [response, setResponse] = useState(null);
  const [filterOpen, setFilterOpen] = useState(false);
  const [fields, setFields] = useState(initialFocus ? defaults.bond : defaults.stock);
  const [busy, setBusy] = useState(false);
  const [enriching, setEnriching] = useState(false);
  const [refresh, setRefresh] = useState(0);
  const [newAxis, setNewAxis] = useState('');
  const [error, setError] = useState('');
  const [update, setUpdate] = useState('');
  const [details, setDetails] = useState(null);
  const [detailsOpen, setDetailsOpen] = useState(false);
  const axes = (response?.axes || []).filter((axis) => draft.kind === 'all' || axis.kinds.includes(draft.kind))
    .map((axis) => ({ ...axis, label: metricLabels[axis.key] || axis.label, group: groupLabels[axis.group] || axis.group }));
  const columns = fields.map((key) => axes.find((axis) => axis.key === key)).filter(Boolean);
  const facets = response?.options || {};
  const set = (name, value) => setDraft((prev) => ({ ...prev, [name]: value }));

  useEffect(() => {
    const controller = new AbortController();
    setBusy(true);
    setError('');
    api('/api/screener', { method: 'POST', body: JSON.stringify(screenParams(active)), signal: controller.signal })
      .then(setResponse)
      .catch((err) => { if (!controller.signal.aborted) setError(err.message); })
      .finally(() => { if (!controller.signal.aborted) setBusy(false); });
    return () => controller.abort();
  }, [active, refresh]);

  function chooseKind(kind) {
    const form = emptyForm(kind);
    setDraft(form);
    setActive(form);
    setFields(defaults[kind]);
    setNewAxis('');
    setResponse(null);
    setUpdate('');
  }

  function apply(event) {
    event?.preventDefault();
    setUpdate('');
    setActive({ ...draft, offset: 0 });
  }

  function changeLimit(key, side, value) {
    set('filters', draft.filters.map((filter) => filter.key === key ? { ...filter, [side]: value } : filter));
  }

  function addFilter(key, min = '', max = '', useNow = false) {
    const filters = [...draft.filters.filter((filter) => filter.key !== key), { key, min, max }];
    const next = { ...draft, filters, offset: 0 };
    setDraft(next);
    setNewAxis('');
    setFilterOpen(true);
    if (useNow) setActive(next);
  }

  async function enrich(assets) {
    if (!assets?.length) return;
    setEnriching(true);
    setUpdate('');
    setError('');
    try {
      const result = await post('/api/screener/enrich', { assets: assets.slice(0, 15) });
      setUpdate(`Loaded more details for ${result.loaded.length} investments${result.unavailable.length ? ` · ${result.unavailable.length} unavailable` : ''}.`);
      setRefresh((old) => old + 1);
    } catch (err) { setError(err.message); }
    finally { setEnriching(false); }
  }

  const page = Math.floor(active.offset / 25) + 1;
  const pages = Math.max(1, Math.ceil((response?.total || 0) / 25));
  const activeFilters = active.filters.filter((filter) => filter.min !== '' || filter.max !== '');
  const selectedAxis = axes.find((axis) => axis.key === newAxis);

  return <div className="discovery-wrap">
    <section className="panel discovery-filter">
      <WithHelp className="screen-kind-choice" label="Type of investment"
        text="Choose a type to see its relevant filters, such as company profits for stocks, annual fees for funds, or interest rates for bonds. All assets combines the available categories.">
        <span className="segmented screen-kinds" aria-label="Type of investment">
          {classes.map(([key, label]) => <button type="button" key={key} aria-pressed={draft.kind === key} onClick={() => chooseKind(key)}>{label}</button>)}
        </span>
      </WithHelp>
      <form onSubmit={apply} autoComplete="off">
        <div className="screen-query-row">
          <WithHelp className="screen-query-help" label="Search this investment type" text="Enter part of a company or fund name, a trading symbol, or an investment code. Press Show results to apply it with your other filters.">
            <label className="screen-query"><Search size={17} /><input aria-label="Search investments by name or code" value={draft.query} onChange={(e) => set('query', e.target.value)} placeholder="Company, fund name, or code" /></label>
          </WithHelp>
          <HelpField className="screen-sort" label="Sort by" text="Choose how to order the results. For example, sort by yearly fund fee and select Lowest first. Then press Show results.">
            <select aria-label="Sort by" value={draft.sort} onChange={(e) => set('sort', e.target.value)}>
              <option value="name">Investment name</option>{axes.map((axis) => <option key={axis.key} value={axis.key}>{axis.label}</option>)}
            </select>
          </HelpField>
          <WithHelp className="screen-order-help" label="Sort direction" text="Choose which end of the list comes first. For an annual fee, Lowest first shows the cheapest available funds at the top.">
            <select aria-label="Sort direction" value={draft.descending ? 'desc' : 'asc'} onChange={(e) => set('descending', e.target.value === 'desc')}>
              <option value="desc">{draft.sort === 'name' ? 'Z to A' : 'Highest first'}</option><option value="asc">{draft.sort === 'name' ? 'A to Z' : 'Lowest first'}</option>
            </select>
          </WithHelp>
          <WithHelp label="Filters" text="Open to choose an industry or category and add numerical ranges. A minimum sets the lowest value allowed and a maximum sets the highest. Leave either end blank for an open range. Press Show results to apply.">
            <button className="button button-outline" type="button" aria-expanded={filterOpen} onClick={() => setFilterOpen(!filterOpen)}><ListFilter size={16} />Filters{activeFilters.length ? ` (${activeFilters.length})` : ''}</button>
          </WithHelp>
          <WithHelp label="Show results" text="Run the search with the selected investment type, filters, and sort order. The matching investments appear below.">
            <button className="button button-primary" type="submit">Show results</button>
          </WithHelp>
        </div>
        {presets[draft.kind] && <div className="screen-presets">
          {presets[draft.kind].map(([label, key, min, max]) => <button className="button button-small button-outline" type="button" key={label} onClick={() => addFilter(key, min, max, true)}>{label}</button>)}
          <Help label="Quick filters" text="Apply a common filter in one click. For example, Profitable looks for positive profit over the last twelve months, and Low expenses sets a limit on the fund’s yearly fee. Open Filters to adjust the ranges." />
        </div>}
        {filterOpen && <div className="screen-filter-body">
          <div className="screen-facets">
            {Object.entries({ sector: 'Industry', category: 'Category', issuer: 'Issuer', exchange: 'Exchange', plan: 'Fund plan', option: 'Fund payout option', rating: 'Reported credit rating', frequency: 'How often interest is paid' }).map(([field, label]) =>
              <Facet key={field} field={field} label={label} request={draft} options={facets[field]} change={set} />)}
          </div>
          <div className="axis-filters">
            {draft.filters.map((filter) => {
              const axis = axes.find((item) => item.key === filter.key);
              if (!axis) return null;
              const covered = response?.coverage?.[filter.key];
              return <div className="axis-row" key={filter.key}>
              <div><WithHelp label={axis.label} text={axisHelp(axis)}><strong>{axis.label}</strong></WithHelp> {unit(axis) && <small>{unit(axis)}</small>}
                  {Number.isFinite(covered) && <small className="axis-cover">{number(covered, 0)} investments have this data</small>}
                </div>
                <input type="number" step="any" placeholder="Min" aria-label={`${axis.label} minimum`} value={filter.min} onChange={(e) => changeLimit(filter.key, 'min', e.target.value)} />
                <input type="number" step="any" placeholder="Max" aria-label={`${axis.label} maximum`} value={filter.max} onChange={(e) => changeLimit(filter.key, 'max', e.target.value)} />
                <button className="icon-button" type="button" aria-label={`Remove ${axis.label} filter`} onClick={() => set('filters', draft.filters.filter((item) => item.key !== filter.key))}><X size={16} /></button>
              </div>;
            })}
          </div>
          <div className="form-actions axis-add">
            <select aria-label="Choose what to filter by" value={newAxis} onChange={(e) => setNewAxis(e.target.value)}>
              <option value="">Choose what to filter by</option>
              {[...new Set(axes.map((axis) => axis.group))].map((group) => <optgroup key={group} label={group}>
                {axes.filter((axis) => axis.group === group && !draft.filters.some((filter) => filter.key === axis.key)).map((axis) =>
                  <option key={axis.key} value={axis.key}>{axis.label}{unit(axis) ? ` (${unit(axis)})` : ''}</option>)}
              </optgroup>)}
            </select>
            <Help label={selectedAxis?.label || 'Choose what to filter by'}
              text={selectedAxis ? axisHelp(selectedAxis) : 'Pick a metric and use Add filter to set its range. The available metrics depend on the investment type, and each filter has an explanation of how its figure is measured.'} />
            <button className="button button-outline" type="button" disabled={!newAxis} onClick={() => addFilter(newAxis)}><Plus size={16} />Add filter</button>
            <WithHelp label="Clear filters" text="Reset the search, ranges, and sort order to the defaults for the current investment type.">
              <button className="button button-outline" type="button" onClick={() => chooseKind(draft.kind)}>Clear filters</button>
            </WithHelp>
          </div>
        </div>}
      </form>
    </section>

    <section className="panel discovery-results">
      <div className="discovery-toolbar">
        <div>
          <HelpTitle label="Matching investments"
            text="These investments match the search and filters you applied. Click a name for its details, a column heading to sort, or the bookmark to save an investment. A dash means that figure is unavailable.">
            {response ? `${number(response.total, 0)} matching investments` : 'Results'}
          </HelpTitle>
          {response && <p>From {number(response.scope_count, 0)} investments{response.session ? ` · NSE closing prices from ${dateLabel(response.session, false)}` : ''}{response.enriched > 0 ? ` · Extra details for ${response.enriched}` : ''}</p>}
        </div>
        <div className="form-actions">
          {axes.length > 0 && <HelpDetails className="columns-menu" wrapperClassName="column-menu-help" label="Columns"
            text="Choose which figures appear in the results table. Each option has a definition. Adding a column changes what you see without applying a value filter."
            summaryProps={{ className: 'button button-small button-outline' }} summary={<><Settings2 size={15} />Columns</>}>
            <div>{axes.map((axis) => <WithHelp key={axis.key} label={axis.label} text={axisHelp(axis)} side="left">
              <label className="check-line"><input type="checkbox" checked={fields.includes(axis.key)}
                onChange={(e) => setFields(e.target.checked ? [...fields, axis.key] : fields.filter((key) => key !== axis.key))} />{axis.label}</label>
            </WithHelp>)}</div>
          </HelpDetails>}
          {response?.enrichment_candidates?.length > 0 && <WithHelp label="Load more details" text="Fetch extra company or price-history data for a subset of the results. When a source has the data, this can fill in missing numbers such as profits or past returns.">
            <button className="button button-small button-outline" type="button" disabled={enriching}
              onClick={() => enrich(response.enrichment_candidates)}>{enriching && <LoaderCircle size={15} className="spin" />}Load more details</button>
          </WithHelp>}
        </div>
      </div>
      {error && <p className="form-error discovery-message" role="alert">{error}</p>}
      {update && <p className="inline-note discovery-message" role="status">{update}</p>}
      {response?.unavailable?.length > 0 && <p className="inline-note discovery-message">Some sources are unavailable · {response.unavailable.join(', ')}</p>}
      {response?.profit_range_match_count > 0 && <p className="inline-note discovery-message"><a href="https://finance.yahoo.com/research-hub/screener/" target="_blank" rel="noreferrer">Yahoo Finance</a> matched {number(response.profit_range_match_count, 0)} additional stocks to your net-income range. Load company profiles to see their reported amounts.</p>}
      {busy && <p className="inline-note discovery-message" role="status">Loading investments…</p>}
      {response && !response.total && !busy && <p className="inline-note discovery-message">No investments match. Try a wider range or remove a filter. Price and financial filters need a published value.</p>}
      {response?.rows?.length > 0 && <div className="table-scroll discovery-table">
        <table><thead><tr>
          <th scope="col"><WithHelp label="Investment" text="The name and identifying code of the investment. Click the name to see its details and sources." /></th>
          <th scope="col"><WithHelp label="Category" text="The investment’s industry, fund category, or type. Additional labels may show the plan or published bond rating." /></th>
          {columns.map((axis) => <th scope="col" key={axis.key}><WithHelp label={axis.label} text={`${axisHelp(axis)} Click the column name to sort by this figure.`}>
            <button className="sort-heading" type="button" onClick={() => {
              const next = { ...active, sort: axis.key, descending: active.sort === axis.key ? !active.descending : true, offset: 0 };
              setActive(next);
              setDraft((prev) => ({ ...prev, sort: next.sort, descending: next.descending }));
            }}>{axis.label}{unit(axis) && ` (${unit(axis)})`}</button>
          </WithHelp></th>)}
          <th scope="col"><WithHelp label="Actions" text="Use the bookmark to put an investment on a saved list for later." /></th>
        </tr></thead>
        <tbody>{response.rows.map((row) => <tr key={row.symbol}>
          <td><button className="asset-table-button" onClick={() => { setDetails(row); setDetailsOpen(true); }}><AssetIdentity asset={row} /></button></td>
          <td className="category-cell">{row.category || row.sector || typeLabel[row.kind]}{row.plan && <small>{row.plan}{row.option && ` · ${row.option}`}</small>}{row.rating && <small>{row.rating} · NSDL</small>}</td>
          {columns.map((axis) => <td key={axis.key} className={`number-cell ${axis.key === 'change' || axis.key.startsWith('return_') ? tone(row.metrics[axis.key]) : ''}`}>
            {axis.key === 'net_income' && row.profit_range_match ? <span title="Yahoo Finance confirms this stock matches your range">In range</span> : formatted(axis, row.metrics[axis.key])}
          </td>)}
          <td><button className="icon-button" type="button" aria-label={`Save ${row.symbol} to wishlist`} title="Save to wishlist" onClick={() => onSave(row)}><Bookmark size={16} /></button></td>
        </tr>)}</tbody></table>
      </div>}
      {response && <div className="discovery-pagination">
        <p className="inline-note"><Info size={14} /> A dash means a value is unavailable. NSE closing prices can show a jump after a stock split. Extra details may include prices adjusted for splits and fund values over time.</p>
        {pages > 1 && <div className="form-actions">
          <button className="button button-small button-outline" disabled={busy || page <= 1} onClick={() => setActive({ ...active, offset: active.offset - 25 })}>Previous</button>
          <span>{page} / {pages}</span>
          <button className="button button-small button-outline" disabled={busy || page >= pages} onClick={() => setActive({ ...active, offset: active.offset + 25 })}>Next</button>
        </div>}
      </div>}
    </section>
    <MarketDetails asset={details} open={detailsOpen} setOpen={setDetailsOpen} axes={axes} onResearch={onResearch} onSave={onSave} />
  </div>;
}

export function WishlistDialog({ asset, close, wishlists, onCreate, onModify }) {
  const title = useRef(null);
  const [name, setName] = useState('');
  const [error, setError] = useState('');
  const [busy, setBusy] = useState(false);
  async function modify(list, included) {
    setBusy(true);
    setError('');
    try { await onModify(list.id, asset, included); }
    catch (err) { setError(err.message); }
    finally { setBusy(false); }
  }
  async function create(event) {
    event.preventDefault();
    setBusy(true);
    setError('');
    try {
      const item = await onCreate(name);
      await onModify(item.id, asset, true);
      setName('');
    } catch (err) { setError(err.message); }
    finally { setBusy(false); }
  }
  return <Dialog.Root open={Boolean(asset)} onOpenChange={(open) => { if (!open) close(); }}>
    <Dialog.Portal>
      <Dialog.Overlay className="dialog-overlay" />
      <Dialog.Content className="search-dialog wishlist-dialog" onOpenAutoFocus={(event) => {
        event.preventDefault();
        title.current?.focus();
      }}>
        <HelpTitle as={Dialog.Title} ref={title} tabIndex={-1} label="Save to a list" text="Tick a list to add this investment, or untick it to remove it from that list. Enter a name and choose Create and save to make a new list." />
        <Dialog.Description>{asset?.name}</Dialog.Description>
        <Dialog.Close className="icon-button dialog-close" aria-label="Close wishlist dialog"><X size={19} /></Dialog.Close>
        <div className="wishlist-choices">
          {wishlists.map((list) => <label className="check-line" key={list.id}>
            <input type="checkbox" disabled={busy} checked={list.assets.some((item) => item.symbol === asset?.symbol)}
              onChange={(e) => modify(list, e.target.checked)} />{list.name}
          </label>)}
        </div>
        <form className="form-actions" onSubmit={create}>
          <input aria-label="New list name" placeholder="New list name" required maxLength={70} value={name} onChange={(e) => setName(e.target.value)} />
          <button className="button button-primary" disabled={busy || !name.trim()} type="submit"><Plus size={15} />Create and save</button>
        </form>
        {error && <p className="form-error" role="alert">{error}</p>}
      </Dialog.Content>
    </Dialog.Portal>
  </Dialog.Root>;
}

export function Wishlists({ wishlists, onCreate, onModify, onDelete, onFind, onResearch }) {
  const [selected, setSelected] = useState(null);
  const [name, setName] = useState('');
  const [error, setError] = useState('');
  const active = wishlists.find((item) => item.id === selected) || wishlists[0];
  async function create(event) {
    event.preventDefault();
    setError('');
    try {
      const item = await onCreate(name);
      setSelected(item.id);
      setName('');
    } catch (err) { setError(err.message); }
  }
  async function perform(action) {
    setError('');
    try { await action(); } catch (err) { setError(err.message); }
  }
  return <div className="collections-grid">
    <section className="panel collection-sidebar">
      <HelpTitle label="Your saved lists" text="Create named groups of investments and switch between them here. The number next to each list counts how many investments it holds." />
      <form className="form-actions" onSubmit={create}>
        <input aria-label="List name" placeholder="Name a list" value={name}
          onChange={(e) => setName(e.target.value)} maxLength={70} required />
        <button className="button button-primary" type="submit" disabled={!name.trim()}>Create</button>
      </form>
      {wishlists.map((list) => <button key={list.id} className={`collection-choice ${active?.id === list.id ? 'collection-selected' : ''}`} onClick={() => setSelected(list.id)}>
        <Bookmark size={16} /><span>{list.name}</span><small>{list.assets.length}</small>
      </button>)}
    </section>
    <section className="panel collection-content">
      <div className="collection-heading">
        <div><HelpTitle label="Saved investments" text="The investments in the selected list. Use Add investment to find another one. You can open research for supported investments or remove an item using the cross.">{active?.name || 'Saved investments'}</HelpTitle>{active && <p>{active.assets.length} saved</p>}</div>
        {active && <div className="form-actions">
          <button className="button button-outline" onClick={() => onFind((asset) => perform(() => onModify(active.id, asset, true)))}><Plus size={16} />Add investment</button>
          <button className="icon-button" title="Delete wishlist" aria-label="Delete wishlist" onClick={() => {
            if (window.confirm(`Delete wishlist “${active.name}”?`)) perform(() => onDelete(active.id));
          }}><Trash2 size={16} /></button>
          <Help label="Manage this list" text="Add investment opens search for this list. The bin deletes this entire list after you confirm. Use the cross beside a single investment to remove only that item." />
        </div>}
      </div>
      {error && <p className="form-error" role="alert">{error}</p>}
      {!active && <div className="empty-list"><Bookmark size={22} /><p>Create a list to save investments you want to revisit.</p></div>}
      {active && !active.assets.length && <div className="empty-list"><Bookmark size={22} /><p>Nothing saved yet. Add your first investment.</p></div>}
      {active?.assets.map((asset) => <div className="collection-item" key={asset.symbol}>
        <AssetIdentity asset={asset} /><span className="asset-type">{typeLabel[asset.kind]}</span>
        {asset.kind !== 'bond' && <button className="button button-small button-outline" onClick={() => onResearch(asset)}>Research</button>}
        <button className="icon-button" aria-label={`Remove ${asset.symbol}`} onClick={() => perform(() => onModify(active.id, asset, false))}><X size={16} /></button>
      </div>)}
    </section>
  </div>;
}
